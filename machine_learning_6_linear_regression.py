"""Machine Learning 6: Linear regression for a continuous target."""
from sklearn.datasets import load_diabetes
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split

def main():
    data = load_diabetes()
    X_train, X_test, y_train, y_test = train_test_split(
        data.data, data.target, test_size=0.2, random_state=42
    )
    model = LinearRegression()
    model.fit(X_train, y_train)
    pred = model.predict(X_test)
    print("MACHINE LEARNING 6 - LINEAR REGRESSION")
    print(f"MAE: {mean_absolute_error(y_test, pred):.2f}")
    print(f"RMSE: {mean_squared_error(y_test, pred) ** 0.5:.2f}")
    print(f"R-squared: {r2_score(y_test, pred):.3f}")
    print("First five predictions:", pred[:5].round(1))
    print("First five actual values:", y_test[:5])

if __name__ == "__main__":
    main()
